-- 数采平台（DC = Data Collection）：设备接入 / 采集点 / 规则 / 流水 / 报警 / 在线日志
-- 移植自 YINJIA 的 bs_dc_* 七张表（SQL Server），方言改 PostgreSQL，审计列统一为 light-mes 风格；
