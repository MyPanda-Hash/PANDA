-- MySQL 的 ON UPDATE CURRENT_TIMESTAMP 在 PG 没有等价语法，用 BEFORE UPDATE 触发器补齐
create or replace function touch_update_time() returns trigger language plpgsql as $$
begin
  new.update_time := clock_timestamp();
  return new;
end $$;

drop trigger if exists trg_form_data_touch on form_data;
create trigger trg_form_data_touch before update on form_data for each row execute function touch_update_time();
drop trigger if exists trg_panel_config_touch on panel_config;
create trigger trg_panel_config_touch before update on panel_config for each row execute function touch_update_time();
drop trigger if exists trg_px_column_pref_touch on px_column_pref;
create trigger trg_px_column_pref_touch before update on px_column_pref for each row execute function touch_update_time();
drop trigger if exists trg_stock_balance_touch on stock_balance;
