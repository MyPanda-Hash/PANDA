-- 系统初始化向导（2026-11-13 决策 D8/D9/D10）
-- 一次性锁 + 分批上传留痕 + 期初余额证据表：初始化允许写业务数据，但一旦完成即锁定，
-- 且期初库存必须留下「原始上传值 / 人工确认值 / 操作人 / 时间」三重可追溯证据。

-- 账套初始化状态（单行）：locked=true 表示已完成初始化，不允许再次导入
create table if not exists init_state (
  id           bigint generated by default as identity not null,
  batch_no     varchar(40),
  modules_done varchar(500),
  locked       boolean     not null default false,
  locked_at    timestamp(0),
  locked_by    varchar(50),
  create_time  timestamp(0) default now(),
  update_time  timestamp(0) default now(),
  constraint pk_init_state primary key (id),
  constraint uk_init_state_singleton unique (id)
);

comment on table init_state is '系统初始化状态：单行；locked=已初始化完成，禁止再次导入';
comment on column init_state.modules_done is '已完成模块（逗号分隔，见 InitModule 编码）';

-- 初始化批次：一次「开始初始化」到「完成」为一个批次
create table if not exists init_batch (
  id          bigint generated by default as identity not null,
  batch_no    varchar(40)  not null,
  operator    varchar(50)  not null,
  status      varchar(20)  not null default '进行中',
  remark      varchar(500),
  create_time timestamp(0) default now(),
  constraint pk_init_batch primary key (id),
  constraint uk_init_batch_no unique (batch_no)
);

comment on table init_batch is '初始化批次：一次初始化过程一行，用于把上传、落库、证据串起来';

-- 初始化明细：本次初始化创建的每一条记录（便于结果页回看与锁前撤销）
create table if not exists init_batch_item (
  id          bigint generated by default as identity not null,
  batch_no    varchar(40) not null,
  module      varchar(30) not null,
  natural_key varchar(200) not null,
  target      varchar(50) not null,
  target_id   bigint,
  action      varchar(20) not null,
  message     varchar(500),
  create_time timestamp(0) default now(),
  constraint pk_init_batch_item primary key (id)
);
create index if not exists idx_init_batch_item_batch on init_batch_item (batch_no, module);

comment on table init_batch_item is '初始化明细：新增/跳过/失败逐条留痕（自然键 + 落库后主键）';

-- 上传原件留痕（不进业务表，只证明「当初上传的是什么」）
create table if not exists init_upload (
  id          bigint generated by default as identity not null,
  batch_no    varchar(40)  not null,
  module      varchar(30)  not null,
  file_name   varchar(200) not null,
  file_size   bigint,
  stored_path varchar(500),
  sha256      varchar(64),
  row_count   integer,
  operator    varchar(50),
  create_time timestamp(0) default now(),
  constraint pk_init_upload primary key (id)
);
create index if not exists idx_init_upload_batch on init_upload (batch_no, module);

comment on table init_upload is '初始化上传原件：文件名/大小/落盘路径/哈希/行数，用于追溯「导入的是哪一版表」';

-- 期初余额证据表：只增不改；_input 是上传原值，_confirmed 是人工核对后的值
create table if not exists init_balance_evidence (
  id                  bigint generated by default as identity not null,
  batch_no            varchar(40)  not null,
  source_file         varchar(200),
  source_row          integer,
  item_code           varchar(50),
  item_name           varchar(100),
  spec                varchar(100),
  unit                varchar(20),
  warehouse_input     varchar(50),
  warehouse_confirmed varchar(50),
  qty_input           numeric(18,4),
  qty_confirmed       numeric(18,4),
  price_input         numeric(18,4),
  price_confirmed     numeric(18,4),
  amount_confirmed    numeric(18,2),
  changed             boolean not null default false,
  init_balance_no     varchar(50),
  voided              boolean not null default false,
  operator            varchar(50),
  confirmed_at        timestamp(0),
  create_time         timestamp(0) default now(),
  constraint pk_init_balance_evidence primary key (id)
);
create index if not exists idx_init_evidence_batch on init_balance_evidence (batch_no);
create index if not exists idx_init_evidence_item on init_balance_evidence (item_code);

comment on table init_balance_evidence is '期初余额证据：上传原值 + 人工确认值 + 操作人/时间，防止期初金额事后扯皮';
comment on column init_balance_evidence.qty_input is '上传文件里的原始数量（写入后不再修改）';
comment on column init_balance_evidence.qty_confirmed is '人工核对后确认的数量（可改，改动会置 changed=true）';
comment on column init_balance_evidence.init_balance_no is '落库后关联的期初余额单号，可反查单据与库存事务';