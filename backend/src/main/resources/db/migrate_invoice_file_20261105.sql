-- 发票官方票面归档（OFD/PDF 回传）
-- 系统不签发发票，正式票面由电子税务局/开票服务商开具后回传归档。
-- 按项目规范预留 30 个扩展列：ext_str1-10 / ext_num1-10 / ext_date1-5 / ext_flag1-5
CREATE TABLE IF NOT EXISTS invoice_file (
  id          BIGINT PRIMARY KEY AUTO_INCREMENT,
  invoice_no  VARCHAR(50)  NOT NULL COMMENT '发票单据号（SALE_INVOICE 编号）',
  file_name   VARCHAR(255) COMMENT '原始文件名',
  file_path   VARCHAR(500) COMMENT '相对存储根目录的路径',
  file_size   BIGINT       COMMENT '字节数',
  file_type   VARCHAR(10)  COMMENT 'OFD / PDF',
  sha256      CHAR(64)     COMMENT '文件指纹，重复上传可识别',
  upload_by   VARCHAR(50)  COMMENT '上传人',
  upload_time DATETIME     DEFAULT CURRENT_TIMESTAMP,
  ext_str1    VARCHAR(200) NULL,
  ext_str2    VARCHAR(200) NULL,
  ext_str3    VARCHAR(200) NULL,
  ext_str4    VARCHAR(200) NULL,
  ext_str5    VARCHAR(200) NULL,
  ext_str6    VARCHAR(200) NULL,
  ext_str7    VARCHAR(200) NULL,
  ext_str8    VARCHAR(200) NULL,
  ext_str9    VARCHAR(200) NULL,
  ext_str10   VARCHAR(200) NULL,
  ext_num1    DECIMAL(18,4) NULL,
  ext_num2    DECIMAL(18,4) NULL,
  ext_num3    DECIMAL(18,4) NULL,
  ext_num4    DECIMAL(18,4) NULL,
  ext_num5    DECIMAL(18,4) NULL,
  ext_num6    DECIMAL(18,4) NULL,
  ext_num7    DECIMAL(18,4) NULL,
  ext_num8    DECIMAL(18,4) NULL,
  ext_num9    DECIMAL(18,4) NULL,
  ext_num10   DECIMAL(18,4) NULL,
  ext_date1   DATETIME NULL,
  ext_date2   DATETIME NULL,
  ext_date3   DATETIME NULL,
  ext_date4   DATETIME NULL,
  ext_date5   DATETIME NULL,
  ext_flag1   TINYINT NULL,
  ext_flag2   TINYINT NULL,
  ext_flag3   TINYINT NULL,
  ext_flag4   TINYINT NULL,
  ext_flag5   TINYINT NULL,
  KEY idx_invoice_no (invoice_no),
  KEY idx_sha256 (sha256)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='发票官方票面文件';
