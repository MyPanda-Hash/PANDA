def build_default_pi_system_prompt(*, persona_name: str, company_name: str) -> str:
    """Render the built-in Pi prompt with the current configured identity."""
    name = persona_name.strip() or ASSISTANT_NAME
    company = company_name.strip() or DEFAULT_COMPANY_NAME
    return DEFAULT_PI_SYSTEM_PROMPT_TEMPLATE.format(
        persona_name=name,
        company_name=company,
    )


