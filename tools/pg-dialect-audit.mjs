#!/usr/bin/env node
/**
 * 数据库方言审计：运行库已换 PostgreSQL，代码里不得再出现 MySQL 专有语法。
 *
 * 覆盖运行路径：后端 Java / application.yml / start-local.sh / tools 脚本 / 前端源码。
 * 不覆盖 backend/src/main/resources/db/*.sql —— 那是回滚窗口内的 MySQL 资产，
 * 结构权威源是 db/migration/V1__baseline.sql（见 db/README.md）。
 *
 * 用法：node light-mes/tools/pg-dialect-audit.mjs
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const WORKSPACE = path.resolve(ROOT, '..')

const RULES = [
  { re: /ON DUPLICATE KEY/gi, why: 'MySQL upsert，PostgreSQL 用 ON CONFLICT' },
  { re: /AUTO_INCREMENT/gi, why: 'MySQL 自增，PostgreSQL 用 generated by default as identity' },
  { re: /ENGINE\s*=\s*InnoDB/gi, why: 'MySQL 存储引擎子句' },
  { re: /DEFAULT\s+CHARSET\s*=/gi, why: 'MySQL 字符集子句' },
  { re: /jdbc:mysql:/gi, why: 'MySQL 连接串' },
  { re: /\bmysqldump\b/gi, why: 'MySQL 备份命令（PostgreSQL 用 pg_dump）' },
  { re: /\bMYSQL_PWD\b/gi, why: 'MySQL 口令变量（PostgreSQL 用 PGPASSWORD）' },
  { re: /\bIFNULL\s*\(/gi, why: 'MySQL 空值函数，PostgreSQL 用 COALESCE' },
  { re: /\bDATE_FORMAT\s*\(/gi, why: 'MySQL 日期格式化，PostgreSQL 用 to_char' },
  { re: /\bGROUP_CONCAT\s*\(/gi, why: 'MySQL 聚合拼接，PostgreSQL 用 string_agg' },
  { re: /\bSET\s+@[a-z_]+/gi, why: 'MySQL 会话变量，PostgreSQL 不支持' },
  { re: /\bTINYINT\b/gi, why: 'MySQL 类型，PostgreSQL 用 boolean/smallint' },
]

const SKIP_DIRS = new Set(['node_modules', 'target', 'dist', '.git', 'backup-prepg'])
const EXT = new Set(['.java', '.yml', '.yaml', '.mjs', '.js', '.vue', '.sh', '.properties'])
/** 生成 PG 结构的工具本身要读 MySQL，允许出现方言关键词 */
const ALLOWLIST = new Set(['tools/mysql2pg-schema.mjs', 'tools/mysql2pg-copy.sh', 'tools/pg-dialect-audit.mjs', 'tools/pg-parity.mjs'])
/** 历史一次性脚本：只对 MySQL 库跑过一次，已落地，不再演进（换库后归档） */
const LEGACY = new Set([
  'tools/gen-pu-req-panel.mjs',
  'tools/migrate-route-panel.mjs',
  'tools/sync-init-pu-req.mjs',
])
/** 行尾标了这个注释表示有意保留（回滚窗口内的双方言分支） */
const MARKER = 'pg-dialect-audit: allow'

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue
    const p = path.join(dir, name)
    const st = statSync(p)
    if (st.isDirectory()) yield* walk(p)
    else if (EXT.has(path.extname(name))) yield p
  }
}

const hits = []
for (const file of walk(path.join(ROOT, 'backend', 'src', 'main'))) scan(file)
for (const file of walk(path.join(ROOT, 'frontend', 'src'))) scan(file)
scan(path.join(ROOT, 'tools'))
scan(path.join(WORKSPACE, 'start-local.sh'))

function scan(target) {
  const st = statSync(target)
  const files = st.isDirectory()
    ? [...walk(target)].filter(f => !f.endsWith('.sql'))
    : [target]
  for (const file of files) {
    const rel = path.relative(ROOT, file)
    if (ALLOWLIST.has(rel) || LEGACY.has(rel)) continue
    const text = readFileSync(file, 'utf8')
    const lines = text.split('\n')
    lines.forEach((line, i) => {
      const trimmed = line.trim()
      if (trimmed.startsWith('*') || trimmed.startsWith('//') || trimmed.startsWith('#')) return // 注释允许提到历史
      if (line.includes(MARKER)) return
      for (const rule of RULES) {
        rule.re.lastIndex = 0
        if (rule.re.test(line)) hits.push({ file: rel, line: i + 1, why: rule.why, text: line.trim().slice(0, 120) })
      }
    })
  }
}

if (hits.length) {
  console.error(`方言审计失败（${hits.length} 处）：`)
  for (const h of hits) console.error(`- ${h.file}:${h.line} ${h.why}\n    ${h.text}`)
  process.exit(1)
}
console.log('方言审计通过：运行路径无 MySQL 专有语法')
