-- 采购需求分析（2026-11-17）
-- 缺口来源快照：计划分析每次显式分析一张销售订单时，把「外购 + 净需求>0」的物料行
-- 落一份快照（plan_no 区分批次），同订单重新分析时旧快照标记失效；
-- 手工补录需求走同一张表（source_type=手工），撤销即 status=撤销。
-- 本表只存来源与缺口，不存进度；已请购/已采购/已到货由业务单据实时汇总。
create table if not exists pu_req_source (
  id            bigint generated by default as identity not null,
  plan_no       varchar(50)  not null default '',
  so_no         varchar(50)  default '',
  customer      varchar(100) default '',
  due_date      varchar(20)  default '',
  material_code varchar(50)  not null,
  material_name varchar(100) default '',
  spec          varchar(100) default '',
  unit          varchar(20)  default '',
  level         int          default 0,
  path          varchar(500) default '',
  gross_qty     numeric(18,4) default 0,
  stock_qty     numeric(18,4) default 0,
  net_qty       numeric(18,4) default 0,
  supply_type   varchar(20)  default '',
  source_type   varchar(20)  not null default '计划',
  supplier      varchar(100) default '',
  remark        varchar(200) default '',
  status        varchar(20)  not null default '有效',
  created_by    varchar(50)  default '',
  create_time   timestamp(0) default now(),
  update_time   timestamp(0) default now(),
  constraint pk_pu_req_source primary key (id)
);
create index if not exists idx_pu_req_source_mat on pu_req_source(material_code, status);
create index if not exists idx_pu_req_source_so on pu_req_source(so_no, status);
