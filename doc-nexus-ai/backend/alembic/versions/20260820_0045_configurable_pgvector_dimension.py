branch_labels = None
depends_on = None


_HNSW_INDEX = "ix_document_embeddings_embedding_hnsw"


def _is_postgresql() -> bool:
    if context.is_offline_mode():
        return True
    return op.get_bind().dialect.name == "postgresql"


def _configured_dimensions() -> int:
    dimensions = settings.embedding_dimensions
    if not isinstance(dimensions, int) or not 1 <= dimensions <= 2000:
        raise RuntimeError(
            "DOC_NEXUS_EMBEDDING_DIMENSIONS must be an integer between 1 and 2000"
        )
    return dimensions


def upgrade() -> None:
    if not _is_postgresql():
        return

    dimensions = _configured_dimensions()
    # Keep vectors generated by an older model. The application filters them
    # out when querying, while new writes use the configured dimension.
    op.execute(f"DROP INDEX IF EXISTS {_HNSW_INDEX}")
    op.execute(
        "ALTER TABLE document_embeddings "
        "ALTER COLUMN embedding TYPE vector "
        "USING embedding::vector"
    )
    op.execute(
        f"CREATE INDEX {_HNSW_INDEX} "
        "ON document_embeddings USING hnsw "
        f"((embedding::vector({dimensions})) vector_cosine_ops) "
        f"WHERE vector_dims(embedding) = {dimensions}"
    )


def downgrade() -> None:
    # A downgrade cannot safely choose one dimension when multiple model
    # generations may coexist in the unbounded vector column.
    return
